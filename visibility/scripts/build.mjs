// Build for Cloudflare Workers:
//   worker/src/seed-pages.json  starting briefs + scores, generated from the shared rules in public/js/rules.js
//   worker/src/playbook.md      from seo/SEO-AEO-PLAYBOOK.md (served to signed-in users only)
//   worker/src/logo.js          the white Premier logo as base64, for the public report
//   dist/premier-visibility-connector.zip  the WordPress plugin, with --zip
import { writeFileSync, copyFileSync, existsSync, mkdirSync, rmSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { PAGES, blank, evaluate, scoreOf } from "../public/js/rules.js";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const seed = PAGES.map((t) => { const b = blank(t); const s = scoreOf(evaluate(b)); return { id: t.id, name: t.name, url: t.url, type: t.type, brief: b, score: s.total, fails: s.fails }; });
writeFileSync(here("../worker/src/seed-pages.json"), JSON.stringify(seed));
console.log(`seed-pages.json: ${seed.length} pages`);

const pb = here("../../seo/SEO-AEO-PLAYBOOK.md");
if (existsSync(pb)) { copyFileSync(pb, here("../worker/src/playbook.md")); console.log("playbook.md copied"); }

const logo = readFileSync(here("../public/img/premier-logo-white.png")).toString("base64");
writeFileSync(here("../worker/src/logo.js"), `// Generated by scripts/build.mjs\nexport const LOGO_WHITE = "${logo}";\n`);

// Bundle the web app's files into the Worker (served by worker/src/index.js behind Cloudflare Access).
import { readdirSync, statSync } from "node:fs";
const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".png": "image/png", ".jpg": "image/jpeg", ".svg": "image/svg+xml", ".txt": "text/plain; charset=utf-8", ".json": "application/json" };
const pubDir = here("../public/");
const files = {};
const walkDir = (dir) => { for (const f of readdirSync(dir)) { const full = dir + f; if (statSync(full).isDirectory()) walkDir(full + "/"); else {
  const rel = "/" + full.slice(pubDir.length), ext = rel.slice(rel.lastIndexOf("."));
  if (!TYPES[ext]) continue;
  const buf = readFileSync(full), text = ext !== ".png" && ext !== ".jpg";
  files[rel] = { type: TYPES[ext], text, body: text ? buf.toString("utf8") : buf.toString("base64") };
} } };
walkDir(pubDir);
writeFileSync(here("../worker/src/static.js"), `// Generated by scripts/build.mjs from public/. Do not edit.\nexport const FILES = ${JSON.stringify(files)};\n`);
console.log(`static.js: ${Object.keys(files).length} files`);

if (process.argv.includes("--zip")) {
  const dist = here("../dist/"); mkdirSync(dist, { recursive: true });
  rmSync(dist + "premier-visibility-hostinger.zip", { force: true });
  const wp = dist + "premier-visibility-connector.zip"; rmSync(wp, { force: true });
  execFileSync("zip", ["-rqX", wp, "premier-visibility-connector"], { cwd: here("../wp-connector/") });
  console.log("dist/premier-visibility-connector.zip written");
}
