-- Premier Visibility on Cloudflare D1 (SQLite). Timestamps are ISO-8601 UTC strings.
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'editor', created_at TEXT NOT NULL, last_seen TEXT
);
CREATE TABLE IF NOT EXISTS pages (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, url TEXT NOT NULL, type TEXT NOT NULL, brief TEXT NOT NULL,
  score INTEGER NOT NULL DEFAULT 0, fails INTEGER NOT NULL DEFAULT 0, version INTEGER NOT NULL DEFAULT 0,
  archived INTEGER NOT NULL DEFAULT 0, updated_at TEXT NOT NULL, updated_by INTEGER, last_audit TEXT
);
CREATE TABLE IF NOT EXISTS page_versions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, page_id TEXT NOT NULL, version INTEGER NOT NULL, brief TEXT NOT NULL,
  score INTEGER NOT NULL, fails INTEGER NOT NULL, changed TEXT NOT NULL DEFAULT '[]', note TEXT NOT NULL DEFAULT '',
  user_id INTEGER, created_at TEXT NOT NULL, UNIQUE (page_id, version)
);
CREATE TABLE IF NOT EXISTS live_snapshots (
  id INTEGER PRIMARY KEY AUTOINCREMENT, page_id TEXT NOT NULL, url TEXT NOT NULL, fetched_at TEXT NOT NULL,
  status INTEGER NOT NULL, data TEXT NOT NULL, hash TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ls_page ON live_snapshots (page_id, fetched_at);
CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, kind TEXT NOT NULL, severity TEXT NOT NULL DEFAULT 'info',
  page_id TEXT, title TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '{}', user_id INTEGER
);
CREATE INDEX IF NOT EXISTS ev_at ON events (at);
CREATE TABLE IF NOT EXISTS monitors (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, url TEXT NOT NULL, must_contain TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1, state TEXT NOT NULL DEFAULT 'unknown', fail_count INTEGER NOT NULL DEFAULT 0,
  last_checked TEXT, last_status INTEGER, last_ms INTEGER, last_error TEXT NOT NULL DEFAULT ''
);
-- Raw checks are kept 14 days (for the 24-hour chart); check_days keeps a daily rollup for long-range uptime.
CREATE TABLE IF NOT EXISTS checks (
  id INTEGER PRIMARY KEY AUTOINCREMENT, monitor_id INTEGER NOT NULL, at TEXT NOT NULL, ok INTEGER NOT NULL,
  status INTEGER, ms INTEGER, error TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ck_mon ON checks (monitor_id, at);
CREATE TABLE IF NOT EXISTS check_days (
  monitor_id INTEGER NOT NULL, day TEXT NOT NULL, total INTEGER NOT NULL DEFAULT 0, ok INTEGER NOT NULL DEFAULT 0,
  ms_sum INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (monitor_id, day)
);
CREATE TABLE IF NOT EXISTS incidents (
  id INTEGER PRIMARY KEY AUTOINCREMENT, monitor_id INTEGER NOT NULL, started_at TEXT NOT NULL, resolved_at TEXT,
  cause TEXT NOT NULL DEFAULT '', in_window INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS maintenance (
  id INTEGER PRIMARY KEY AUTOINCREMENT, kind TEXT NOT NULL, title TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'general', starts_at TEXT NOT NULL, ends_at TEXT, user_id INTEGER,
  auto INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS wp_snapshots (id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, channel TEXT NOT NULL, subject TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '', ok INTEGER NOT NULL, error TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, value TEXT NOT NULL);
